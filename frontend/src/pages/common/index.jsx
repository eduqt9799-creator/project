import { useCallback, useEffect, useMemo, useState } from 'react';
import { useAuth } from '../../context/AuthContext';
import { authApi, departmentsApi, notificationsApi } from '../../services/api';
import {
  Alert, Badge, Card, CardBody, CardHeader, DataTable, EmptyState, ErrorState, Grid, LoadingState,
  Modal, PageHeader, PasswordInput, SelectInput, StatCard, StatusBadge, TextArea, TextInput, useToast,
} from '../../components/ui';
import { IconBell, IconCheck, IconInbox, IconRefresh, IconShield } from '../../components/Icons';

const toBool = (value) => {
  if (typeof value === 'boolean') return value;
  if (value === undefined || value === null) return false;
  const text = String(value).trim().toLowerCase();
  return text === 'true' || text === '1' || text === 'yes' || text === 'y';
};

const typeTone = (type) => {
  switch (String(type || '').toLowerCase()) {
    case 'success': return 'success';
    case 'warning': return 'warning';
    case 'error': return 'danger';
    default: return 'info';
  }
};

const formatDateTime = (value) => {
  if (!value) return '';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return String(value);
  return date.toLocaleString(undefined, { dateStyle: 'medium', timeStyle: 'short' });
};

/* ---------------------------------------------------------- notifications */

export const NotificationsPage = ({ canSend }) => {
  const { role } = useAuth();
  const toast = useToast();
  const allowSend = canSend ?? ['admin', 'hod'].includes(role);
  const [filter, setFilter] = useState('all');
  const [type, setType] = useState('');
  const [state, setState] = useState({ loading: true, error: '', rows: [], unread: 0 });

  const load = useCallback(async () => {
    setState((s) => ({ ...s, loading: true, error: '' }));
    try {
      const res = await notificationsApi.list({ isRead: filter === 'unread' ? 'false' : filter === 'read' ? 'true' : undefined, type: type || undefined });
      setState({ loading: false, error: '', rows: res.data || [], unread: res.unreadCount ?? 0 });
    } catch (error) {
      setState({ loading: false, error: error.message, rows: [], unread: 0 });
    }
  }, [filter, type]);

  useEffect(() => { load(); }, [load]);

  const markRead = async (row) => {
    try {
      await notificationsApi.markRead(row.notificationId);
      await load();
    } catch (error) {
      toast.error('Could not mark as read', error.message);
    }
  };

  const markAll = async () => {
    try {
      const res = await notificationsApi.markAllRead();
      toast.success('Notifications updated', res.message);
      await load();
    } catch (error) {
      toast.error('Could not mark all as read', error.message);
    }
  };

  return (
    <>
      <PageHeader
        title="Notifications"
        subtitle="Alerts generated by attendance, announcements and academic activity."
        actions={(
          <>
            <button type="button" className="btn btn-secondary" onClick={load}><IconRefresh size={16} />Refresh</button>
            <button type="button" className="btn btn-primary" onClick={markAll} disabled={state.unread === 0}><IconCheck size={16} />Mark all read</button>
            {allowSend ? <SendNotificationButton onSent={load} /> : null}
          </>
        )}
      />
      <Grid>
        <StatCard label="Notifications" value={state.rows.length} icon={<IconBell size={20} />} />
        <StatCard label="Unread" value={state.unread} tone="warning" icon={<IconInbox size={20} />} />
        <StatCard label="Showing" value={filter === 'all' ? 'All' : filter === 'unread' ? 'Unread' : 'Read'} hint={`Type: ${type || 'any'}`} icon={<IconInbox size={20} />} />
      </Grid>
      <div className="mt-2">
        <Card>
          <CardHeader title="Your notifications" actions={(
            <div className="filterbar">
              <SelectInput label="Read state" value={filter} onChange={(e) => setFilter(e.target.value)}
                options={[{ value: 'all', label: 'All' }, { value: 'unread', label: 'Unread' }, { value: 'read', label: 'Read' }]} />
              <SelectInput label="Type" value={type} onChange={(e) => setType(e.target.value)} placeholder="All types"
                options={[{ value: 'info', label: 'Information' }, { value: 'success', label: 'Success' }, { value: 'warning', label: 'Warning' }, { value: 'error', label: 'Error' }]} />
            </div>
          )} />
          <CardBody tight>
            {state.loading ? <LoadingState label="Loading notifications..." />
              : state.error ? <ErrorState message={state.error} onRetry={load} />
              : state.rows.length === 0 ? <EmptyState title="No notifications available." description="Notifications about attendance, assignments, marks and announcements appear here." />
              : (
                <div className="notification-list">
                  {state.rows.map((n) => (
                    <article key={n.notificationId} className={`notification-item ${toBool(n.isRead) ? 'read' : 'unread'}`}>
                      <div className="notification-main">
                        <div className="notification-title">
                          <Badge tone={typeTone(n.type)}>{n.type || 'info'}</Badge>
                          <span className="strong">{n.title}</span>
                          {!toBool(n.isRead) ? <Badge tone="warning">New</Badge> : null}
                        </div>
                        <div className="notification-body">{n.message}</div>
                        <div className="notification-meta">
                          {formatDateTime(n.createdAt)}
                          {n.readAt ? ` · read ${formatDateTime(n.readAt)}` : ''}
                          {n.link ? <> · <a href={n.link} target="_blank" rel="noreferrer">Open</a></> : null}
                        </div>
                      </div>
                      {!toBool(n.isRead) ? (
                        <button type="button" className="btn btn-secondary btn-sm" onClick={() => markRead(n)}>Mark read</button>
                      ) : null}
                    </article>
                  ))}
                </div>
              )}
          </CardBody>
        </Card>
      </div>
    </>
  );
};

const SendNotificationButton = ({ onSent }) => {
  const { isAdmin } = useAuth();
  const toast = useToast();
  const [open, setOpen] = useState(false);
  const [values, setValues] = useState({ userId: '', title: '', message: '', type: 'info' });
  const [errors, setErrors] = useState({});
  const [users, setUsers] = useState([]);
  const [saving, setSaving] = useState(false);

  useEffect(() => {
    if (!open) return;
    setSaving(true);
    notificationsApi.recipients()
      .then((res) => setUsers(res.data || []))
      .catch(() => setUsers([]))
      .finally(() => setSaving(false));
  }, [open]);

  const submit = async (event) => {
    event.preventDefault();
    const nextErrors = {};
    if (!values.userId) nextErrors.userId = 'Select a recipient';
    if (!values.title || values.title.trim().length < 3) nextErrors.title = 'Enter at least 3 characters';
    if (!values.message || values.message.trim().length < 3) nextErrors.message = 'Enter at least 3 characters';
    setErrors(nextErrors);
    if (Object.keys(nextErrors).length) return;

    setSaving(true);
    try {
      await notificationsApi.send({ ...values });
      toast.success('Notification sent');
      setOpen(false);
      setValues({ userId: '', title: '', message: '', type: 'info' });
      onSent?.();
    } catch (error) {
      if (error.fieldErrors) setErrors(error.fieldErrors);
      toast.error('Could not send notification', error.message);
    } finally {
      setSaving(false);
    }
  };

  return (
    <>
      <button type="button" className="btn btn-primary" onClick={() => setOpen(true)}><IconBell size={16} />Send notification</button>
      <Modal
        open={open}
        title="Send notification"
        size="narrow"
        onClose={() => setOpen(false)}
        footer={(
          <>
            <button type="button" className="btn btn-secondary" onClick={() => setOpen(false)} disabled={saving}>Cancel</button>
            <button type="submit" form="send-notification-form" className="btn btn-primary" disabled={saving}>
              {saving ? <span className="spinner" /> : 'Send'}
            </button>
          </>
        )}
      >
        <form id="send-notification-form" onSubmit={submit} noValidate>
          <SelectInput
            label="Recipient"
            required
            value={values.userId}
            onChange={(e) => setValues((p) => ({ ...p, userId: e.target.value }))}
            error={errors.userId}
            disabled={saving}
            placeholder={isAdmin ? 'Select any active user' : 'Select a user in your department'}
            options={users.map((u) => ({ value: u.userId, label: `${u.name} · ${u.role}${u.departmentName ? ` · ${u.departmentName}` : ''}` }))}
            hint={isAdmin ? undefined : 'The backend rejects recipients outside your department.'}
          />
          <TextInput label="Title" required value={values.title} onChange={(e) => setValues((p) => ({ ...p, title: e.target.value }))} error={errors.title} />
          <TextArea label="Message" required value={values.message} onChange={(e) => setValues((p) => ({ ...p, message: e.target.value }))} error={errors.message} />
          <SelectInput label="Type" value={values.type} onChange={(e) => setValues((p) => ({ ...p, type: e.target.value }))}
            options={[{ value: 'info', label: 'Information' }, { value: 'success', label: 'Success' }, { value: 'warning', label: 'Warning' }, { value: 'error', label: 'Error' }]} />
        </form>
      </Modal>
    </>
  );
};

