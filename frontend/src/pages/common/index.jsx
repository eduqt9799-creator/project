export const ProfilePage = () => {
  const { user, departmentName, isAdmin, refresh } = useAuth();
  const toast = useToast();
  const [departments, setDepartments] = useState([]);
  const [values, setValues] = useState({});
  const [errors, setErrors] = useState({});
  const [saving, setSaving] = useState(false);

  useEffect(() => {
    if (!isAdmin) return;
    departmentsApi.list().then((res) => setDepartments(res.data || [])).catch(() => setDepartments([]));
  }, [isAdmin]);

  useEffect(() => {
    if (!user) return;
    setValues({ name: user.name || '', email: user.email || '', phone: user.phone || '' });
  }, [user]);

  const roleRows = useMemo(() => {
    const rows = [
      { label: 'Register number', value: user?.registerNumber },
      { label: 'Semester', value: user?.semester },
      { label: 'Batch', value: user?.batch },
      { label: 'Employee ID', value: user?.employeeId },
      { label: 'Designation', value: user?.designation },
      { label: 'Department code', value: user?.department?.departmentCode },
    ];
    return rows.filter((row) => row.value !== undefined && row.value !== null && row.value !== '');
  }, [user]);

  const save = async (event) => {
    event.preventDefault();
    const nextErrors = {};
    if (!values.name || values.name.trim().length < 2) nextErrors.name = 'Enter at least 2 characters';
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(values.email.trim())) nextErrors.email = 'Enter a valid email address';
    if (values.phone && !/^[0-9+\-\s]{6,15}$/.test(values.phone)) nextErrors.phone = 'Enter a valid phone number';
    setErrors(nextErrors);
    if (Object.keys(nextErrors).length) return;

    setSaving(true);
    try {
      const res = await authApi.updateProfile(values);
      await refresh();
      toast.success('Profile updated', res.message || 'Your details were saved.');
    } catch (error) {
      if (error.fieldErrors) setErrors(error.fieldErrors);
      toast.error('Could not update profile', error.message);
    } finally {
      setSaving(false);
    }
  };

  if (!user) return <LoadingState label="Loading profile..." />;

  return (
    <>
      <PageHeader
        title="My Profile"
        subtitle="Your account details. Role and department are assigned by an administrator."
        actions={(
          <button type="submit" form="profile-form" className="btn btn-primary" disabled={saving}>
            {saving ? <span className="spinner" /> : 'Save changes'}
          </button>
        )}
      />
      <Grid>
        <StatCard label="Role" value={String(user.role || '').toUpperCase()} icon={<IconShield size={20} />} hint="Re-authorised by the backend on every request" />
        <StatCard label="Department" value={departmentName || 'All departments'} hint={user.department?.departmentCode || 'Administrator'} icon={<IconShield size={20} />} />
        <StatCard label="Status" value={user.status === 'active' ? 'Active' : 'Inactive'} tone={user.status === 'active' ? 'success' : 'danger'} />
      </Grid>
      <div className="mt-2">
        <Card>
          <CardHeader title="Account details" subtitle="Changes apply immediately. Your linked academic record is updated to match." />
          <CardBody>
            <form id="profile-form" onSubmit={save} noValidate>
              <div className="form-grid">
                <TextInput label="Name" required value={values.name || ''} onChange={(e) => setValues((p) => ({ ...p, name: e.target.value }))} error={errors.name} />
                <TextInput label="Email" type="email" required value={values.email || ''} onChange={(e) => setValues((p) => ({ ...p, email: e.target.value }))} error={errors.email} hint="Used to sign in" />
                <TextInput label="Phone" value={values.phone || ''} onChange={(e) => setValues((p) => ({ ...p, phone: e.target.value }))} error={errors.phone} />
              </div>
            </form>
          </CardBody>
        </Card>
      </div>
      <div className="mt-2">
        <Card>
          <CardHeader title="Role-specific information" subtitle="Read-only values loaded from your account profile" />
          <CardBody>
            {roleRows.length === 0 ? <EmptyState title="No profile records available." description="Your account is not linked to a student, faculty or HOD record yet." /> : (
              <div className="table-wrap">
                <table className="data-table">
                  <thead><tr><th scope="col">Field</th><th scope="col">Value</th></tr></thead>
                  <tbody>
                    {roleRows.map((row) => (
                      <tr key={row.label}>
                        <td className="strong">{row.label}</td>
                        <td>{String(row.value)}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </CardBody>
        </Card>
      </div>
      {isAdmin ? (
        <div className="mt-2">
          <Card>
            <CardHeader title="Departments" subtitle="Loaded live from the department records" />
            <CardBody tight>
              <DataTable
                rows={departments}
                keyField="departmentId"
                emptyTitle="No department records available."
                columns={[
                  { key: 'departmentCode', header: 'Code', render: (r) => <span className="mono strong">{r.departmentCode}</span> },
                  { key: 'departmentName', header: 'Name' },
                  { key: 'hodName', header: 'HOD', render: (r) => r.hodName || '—' },
                  { key: 'status', header: 'Status', render: (r) => <StatusBadge status={r.status} /> },
                ]}
              />
            </CardBody>
          </Card>
        </div>
      ) : null}
    </>
  );
};

/* --------------------------------------------------------------- security */

export const SecurityPage = () => {
  const toast = useToast();
  const [values, setValues] = useState({ currentPassword: '', newPassword: '', confirmPassword: '' });
  const [errors, setErrors] = useState({});
  const [saving, setSaving] = useState(false);

  const submit = async (event) => {
    event.preventDefault();
    const nextErrors = {};
    if (!values.currentPassword) nextErrors.currentPassword = 'Enter your current password';
    if (values.newPassword.length < 8) nextErrors.newPassword = 'Minimum 8 characters';
    else if (!/[A-Za-z]/.test(values.newPassword) || !/[0-9]/.test(values.newPassword)) nextErrors.newPassword = 'Include at least one letter and one number';
    if (values.newPassword !== values.confirmPassword) nextErrors.confirmPassword = 'Passwords do not match';
    setErrors(nextErrors);
    if (Object.keys(nextErrors).length) return;

    setSaving(true);
    try {
      const res = await authApi.changePassword(values.currentPassword, values.newPassword);
      toast.success('Password updated', res.message || 'Use the new password the next time you sign in.');
      setValues({ currentPassword: '', newPassword: '', confirmPassword: '' });
    } catch (error) {
      if (error.fieldErrors) setErrors(error.fieldErrors);
      toast.error('Could not change password', error.message);
    } finally {
      setSaving(false);
    }
  };

  return (
    <>
      <PageHeader title="Security" subtitle="Change the password used to sign in to this ERP." />
      <Card>
        <CardHeader title="Change password" subtitle="Passwords are hashed with bcrypt on the server and never returned." />
        <CardBody>
          <Alert tone="info" title="Password policy">Minimum 8 characters with at least one letter and one number.</Alert>
          <form className="mt-2" onSubmit={submit} noValidate>
            <div className="form-grid">
              <PasswordInput label="Current password" required value={values.currentPassword} onChange={(e) => setValues((p) => ({ ...p, currentPassword: e.target.value }))} error={errors.currentPassword} />
              <PasswordInput label="New password" required value={values.newPassword} onChange={(e) => setValues((p) => ({ ...p, newPassword: e.target.value }))} error={errors.newPassword} />
              <PasswordInput label="Confirm new password" required value={values.confirmPassword} onChange={(e) => setValues((p) => ({ ...p, confirmPassword: e.target.value }))} error={errors.confirmPassword} />
            </div>
            <div className="form-actions">
              <button type="submit" className="btn btn-primary" disabled={saving}>{saving ? <span className="spinner" /> : 'Update password'}</button>
            </div>
          </form>
        </CardBody>
      </Card>
    </>
  );
};